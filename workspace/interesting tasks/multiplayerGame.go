// Представим, что мы разрабатываем сетевую игру, необходимо реализовать
// возможность ожидания подключения всех игроков. Пример на использование
// sync.Cond, пояснения после кода

package main

import (
	"fmt"
	"sync"
	"time"
)

func main() {
	// Создаем условную переменную с мьютексом
	cond := sync.NewCond(&sync.Mutex{})
	players := 0    // Текущее количество подключенных игроков
	needed := 3     // Необходимое количество игроков для начала игры
	ready := false  // Флаг готовности игры к началу
	cancel := false // Флаг отмены игры по таймауту

	// Горутина для обработки таймаута
	go func() {
		time.Sleep(2 * time.Second) // Ждем 2 секунды
		cond.L.Lock()               // Захватываем мьютекс
		cancel = true               // Устанавливаем флаг отмены
		cond.Broadcast()            // Будим все ожидающие горутины
		cond.L.Unlock()             // Освобождаем мьютекс
		fmt.Println("Таймаут!")     // Сообщаем о таймауте
	}()

	// Функция подключения игрока
	join := func(id int) {
		cond.L.Lock()         // Захватываем мьютекс для работы с общими данными
		defer cond.L.Unlock() // Гарантируем освобождение мьютекса при выходе

		players++ // Увеличиваем счетчик игроков
		fmt.Printf("Игрок %d (%d/%d)\n", id, players, needed)

		// Проверяем, набралось ли нужное количество игроков
		if players == needed {
			ready = true     // Устанавливаем флаг готовности
			cond.Broadcast() // Будим всех ожидающих игроков
		}

		// Ждем пока игра не будет готова или не отменена
		// Цикл нужен для защиты от ложных пробуждений (spurious wakeups)
		for !ready && !cancel {
			fmt.Printf("Игрок %d ждет...\n", id)
			cond.Wait() // Освобождает мьютекс и ждет сигнала
			// При пробуждении мьютекс автоматически захватывается снова
		}

		// Проверяем причину выхода из ожидания
		if cancel {
			fmt.Printf("❌ Игрок %d: игра отменена\n", id)
		} else {
			fmt.Printf("✅ Игрок %d: начинаем!\n", id)
		}
	}

	// Подключаем 3 игроков
	for i := 1; i <= 3; i++ {
		go join(i)                          // Запускаем горутину игрока
		time.Sleep(1600 * time.Millisecond) // Имитируем задержку между подключениями 1.6 секунды
	}

	// Даем время для выполнения всех операций
	time.Sleep(5 * time.Second)
}

// Ключевые комментарии:
// Условная переменная - синхронизирует горутины на основе условий.
// Мьютекс - защищает доступ к общим переменным players, ready, cancel.
// Broadcast() - пробуждает все ожидающие горутины.
// Wait() - атомарно отпускает мьютекс и ждет сигнала.
// Цикл ожидания - защита от ложных пробуждений (стандартная практика).
// Таймаут - гарантирует, что игра не будет ждать вечно.
// Принцип работы:
// Игроки подключаются по одному.
// Если не хватает игроков - ждут через cond.Wait().
// При подключении последнего игрока - cond.Broadcast() будит всех.
// Если срабатывает таймаут - игра отменяется.

// тестирование - от разных интервалов времени подключения игроков
// и наступления времени таймаута зависит подключатся ли игроки,
// а также возникает вероятность появления гонки условий
